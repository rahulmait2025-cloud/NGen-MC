function SidebarRail({ className, ...props }: React.ComponentProps<"button">) {
  const { toggleSidebar, state, width, setWidth, isMobile, setIsResizing } = useSidebar()
  const dragRef = React.useRef<{ startX: number; startWidth: number; moved: boolean } | null>(
    null
  )

  const setGlobalResizing = React.useCallback(
    (active: boolean) => {
      setIsResizing(active)
      if (typeof document === "undefined") {
        return
      }
      document.body.style.cursor = active ? "col-resize" : ""
      document.body.style.userSelect = active ? "none" : ""
    },
    [setIsResizing]
  )

  const handlePointerDown = (event: React.PointerEvent<HTMLButtonElement>) => {
    if (isMobile || state !== "expanded") {
      return
    }
    event.preventDefault()
    dragRef.current = {
      startX: event.clientX,
      startWidth: width,
      moved: false,
    }
    setGlobalResizing(true)
    event.currentTarget.setPointerCapture(event.pointerId)
  }

  const handlePointerMove = (event: React.PointerEvent<HTMLButtonElement>) => {
    const drag = dragRef.current
    if (!drag) {
      return
    }
    const delta = event.clientX - drag.startX
    if (Math.abs(delta) > 2) {
      drag.moved = true
    }
    setWidth(drag.startWidth + delta)
  }

  const endDrag = (event: React.PointerEvent<HTMLButtonElement>) => {
    const drag = dragRef.current
    if (!drag) {
      return
    }
    if (event.currentTarget.hasPointerCapture(event.pointerId)) {
      event.currentTarget.releasePointerCapture(event.pointerId)
    }
    dragRef.current = null
    setGlobalResizing(false)
    if (!drag.moved) {
      toggleSidebar()
    }
  }

  return (
    <button
      type="button"
      data-sidebar="rail"
      data-slot="sidebar-rail"
      aria-label="Resize sidebar. Click without dragging to collapse."
      tabIndex={0}
      onPointerDown={handlePointerDown}
      onPointerMove={handlePointerMove}
      onPointerUp={endDrag}
      onPointerCancel={endDrag}
      title="Drag to resize * Click to collapse"
      className={cn(
        "absolute top-0 bottom-0 z-40 hidden w-3 md:flex touch-none",
        "cursor-col-resize select-none",
        "group-data-[side=left]:left-[100%] group-data-[side=left]:right-auto group-data-[side=left]:-translate-x-1/2",
        "group-data-[side=right]:right-[100%] group-data-[side=right]:left-auto group-data-[side=right]:translate-x-1/2",
        "group-data-[collapsible=offcanvas]:translate-x-0",
        "[[data-side=left][data-collapsible=offcanvas]_&]:-right-2",
        "[[data-side=right][data-collapsible=offcanvas]_&]:-left-2",
        "group-data-[state=collapsed]:hidden",
        "after:absolute after:inset-y-0 after:left-1/2 after:w-px after:-translate-x-1/2 after:bg-sidebar-border after:transition-colors after:ease-[var(--ease-out)] hover:after:bg-primary/60",
        className
      )}
      {...props}
    >
      <span className="sr-only">Resize sidebar</span>
    </button>
  )
}

